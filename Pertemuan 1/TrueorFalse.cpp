#include <iostream>
using namespace std;

int main() {
    int a = 2, b = 3; // deklarasi dan inisialisasi variabel a dan b dengan nilai 2 dan 3
    cout << "Apakah a lebih besar dari b? " << (a > b) << endl; // menggunakan operator > untuk membandingkan nilai a dan b, kemudian mencetak hasil
    cout << "Apakah a lebih kecil dari b? " << (a < b) << endl; // menggunakan operator < untuk membandingkan nilai a dan b, kemudian mencetak hasil
    cout << "Apakah a sama dengan b? " << (a == b) << endl; // menggunakan operator == untuk membandingkan nilai a dan b, kemudian mencetak hasil
    return 0;
}